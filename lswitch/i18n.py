    def _detect_language(self) -> str:
        """Определяет язык системы."""
        try:
            lang = os.environ.get('LANG', '')
            if lang:
                return 'ru' if lang.startswith('ru') else 'en'

            system_locale = locale.getlocale()[0]
            if system_locale and system_locale.startswith('ru'):
                return 'ru'
        except Exception:
            pass

        return 'en'

